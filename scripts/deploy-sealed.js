// Deploy Sealed Paper to NEAR testnet. Prints the plan by default; --broadcast signs.
//   parent   (CONTRACT_OWNER) creates and funds, signing through near CLI's system keychain
//            (or CONTRACT_PRIVATE_KEY when set):
//   operator SEAL_OPS_ACCOUNT = sealops.<parent> : release service (creates seals, logs open
//                                                 attempts and alerts, funds holder accounts)
//   contract SEAL_CONTRACT    = sealed.<parent>  : contract code, initialized with owner = parent
// New private keys are generated locally and appended to .env. They are never printed.
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { Account, JsonRpcProvider, KeyPair, KeyPairSigner, actions } from 'near-api-js';

const parent = process.env.CONTRACT_OWNER;
if (process.env.NEAR_NETWORK !== 'testnet') throw new Error('Set NEAR_NETWORK=testnet');
if (!parent || !parent.endsWith('.testnet')) throw new Error('Set CONTRACT_OWNER to a testnet account');
const contract = process.env.SEAL_CONTRACT || `sealed.${parent}`, ops = process.env.SEAL_OPS_ACCOUNT || `sealops.${parent}`;
const NEAR = 10n ** 24n;
const wasm = fs.readFileSync(new URL('../contract/build/sealed_paper.wasm', import.meta.url));
const plan = { network: 'testnet', signer: parent, wasmSha256: createHash('sha256').update(wasm).digest('hex'), wasmBytes: wasm.length,
  transactions: [
    { create: ops, deposit: '3 NEAR', key: 'new full-access key (release service)' },
    { create: contract, deposit: '4 NEAR', key: 'new full-access key', then: ['DeployContract', `new(owner=${parent}, operators=[${ops}])`] },
  ] };
console.log(JSON.stringify(plan, null, 2));
if (!process.argv.includes('--broadcast')) { console.log('Plan only. Run with --broadcast to sign.'); process.exit(0); }

const rpc = String(process.env.NEAR_RPC_URLS || '').split(',')[0].trim();
if (!rpc) throw new Error('Set NEAR_RPC_URLS in .env');
const provider = new JsonRpcProvider({ url: rpc });
if ((await provider.viewNodeStatus()).chain_id !== 'testnet') throw new Error('RPC network mismatch');
const exists = async (id) => provider.viewAccount({ accountId: id, blockQuery: { finality: 'final' } }).then(() => true, () => false);
for (const id of [ops, contract]) if (await exists(id)) throw new Error(`${id} already exists; refusing to overwrite`);

// Reuse keys saved by an earlier interrupted run; otherwise generate and save them first,
// so a crash mid-way never loses access to funded accounts.
const reuse = process.env.SEAL_OPS_PRIVATE_KEY && process.env.SEAL_CONTRACT_PRIVATE_KEY;
const opsKey = reuse ? KeyPair.fromString(process.env.SEAL_OPS_PRIVATE_KEY) : KeyPair.fromRandom('ed25519');
const contractKey = reuse ? KeyPair.fromString(process.env.SEAL_CONTRACT_PRIVATE_KEY) : KeyPair.fromRandom('ed25519');
if (!reuse) fs.appendFileSync('.env', [
  '', '# Sealed Paper (testnet), generated by scripts/deploy-sealed.js',
  `SEAL_CONTRACT=${contract}`, `SEAL_CONTRACT_PRIVATE_KEY=${contractKey.toString()}`,
  `SEAL_OPS_ACCOUNT=${ops}`, `SEAL_OPS_PRIVATE_KEY=${opsKey.toString()}`, '',
].join('\n'));

const TX = /([1-9A-HJ-NP-Za-km-z]{43,44})/;
async function createAccount(id, amount, publicKey) {
  if (process.env.CONTRACT_PRIVATE_KEY) {
    const parentAccount = new Account(parent, provider, KeyPairSigner.fromSecretKey(process.env.CONTRACT_PRIVATE_KEY));
    const tx = await parentAccount.signAndSendTransaction({ receiverId: id, waitUntil: 'FINAL', throwOnFailure: true, retries: 0,
      actions: [actions.createAccount(), actions.transfer(BigInt(amount) * NEAR), actions.addFullAccessKey(publicKey)] });
    return tx.transaction.hash;
  }
  const r = spawnSync('near', ['account', 'create-account', 'fund-myself', id, process.platform === 'win32' ? `"${amount} NEAR"` : `${amount} NEAR`, 'use-manually-provided-public-key',
    publicKey.toString(), 'sign-as', parent, 'network-config', 'testnet', 'sign-with-keychain', 'send'], { encoding: 'utf8', shell: process.platform === 'win32' });
  const out = `${r.stdout || ''}${r.stderr || ''}`;
  if (r.status !== 0 || !(await exists(id))) throw new Error(`near CLI could not create ${id}:\n${out.slice(-800)}`);
  const line = out.split('\n').find((l) => /Transaction ID|transaction/i.test(l) && TX.test(l));
  return line ? TX.exec(line)[1] : 'see near CLI output';
}
const opsTx = await createAccount(ops, 3, opsKey.getPublicKey());
console.log(`Created ${ops}: ${opsTx}`);
const contractCreateTx = await createAccount(contract, 4, contractKey.getPublicKey());
console.log(`Created ${contract}: ${contractCreateTx}`);
const contractAccount = new Account(contract, provider, KeyPairSigner.fromSecretKey(contractKey.toString()));
const deploy = await contractAccount.signAndSendTransaction({ receiverId: contract, waitUntil: 'FINAL', throwOnFailure: true, retries: 0,
  actions: [actions.deployContract(wasm), actions.functionCall('new', { owner: parent, operators: [ops] }, 100000000000000n, 0n)] });
console.log(`Deployed ${contract}: ${deploy.transaction.hash}`);
const record = { network: 'testnet', contract, owner: parent, operator: ops, wasmSha256: plan.wasmSha256,
  createOperatorTx: opsTx, createContractTx: contractCreateTx, deployTx: deploy.transaction.hash, deployedAt: new Date().toISOString(),
  explorer: { contract: `${process.env.NEAR_EXPLORER_URL}/address/${contract}`, deployTx: `${process.env.NEAR_EXPLORER_URL}/txns/${deploy.transaction.hash}` } };
fs.writeFileSync('docs/SEALED-DEPLOYMENT.json', JSON.stringify(record, null, 2) + '\n');
console.log(JSON.stringify(record.explorer, null, 2));
